// Package codegen lowers the type-checked Aster AST to a self-contained Go program.
// The Go backend is an initial native backend; generated executables include
// Aster runtime checks rather than relying on unchecked Go arithmetic.
package codegen

import (
	"bytes"
	"fmt"
	"strconv"
	"strings"

	"github.com/aster-lang/aster/internal/ast"
)

type typeScope struct {
	types  map[string]string
	parent *typeScope
}

func newTypeScope(p *typeScope) *typeScope { return &typeScope{types: map[string]string{}, parent: p} }
func (s *typeScope) find(n string) (string, bool) {
	for x := s; x != nil; x = x.parent {
		v, ok := x.types[n]
		if ok {
			return v, true
		}
	}
	return "", false
}

type generator struct {
	tree    *ast.Program
	out     bytes.Buffer
	indent  int
	scope   *typeScope
	returns map[string]string
}

// Generate returns native-backend source. The resulting file can be compiled by
// the Go toolchain; users of Aster do not need to edit the generated source.
func Generate(tree *ast.Program) (string, error) {
	g := &generator{tree: tree, returns: map[string]string{}}
	for _, d := range tree.Decls {
		if f, ok := d.(*ast.Function); ok {
			g.returns[f.Name] = "unit"
			if f.ReturnType != nil {
				g.returns[f.Name] = sourceTypeName(*f.ReturnType)
			}
		}
	}
	g.writePreamble()
	for _, d := range tree.Decls {
		f, ok := d.(*ast.Function)
		if !ok {
			continue
		}
		if err := g.function(f); err != nil {
			return "", err
		}
	}
	g.line("func main() {")
	g.indent++
	g.line("defer func() { if r := recover(); r != nil { fmt.Fprintln(os.Stderr, \"Aster runtime error:\", r); os.Exit(1) } }()")
	g.scope = newTypeScope(nil)
	for _, d := range tree.Decls {
		sd, ok := d.(*ast.StmtDecl)
		if !ok {
			continue
		}
		if err := g.statement(sd.Statement); err != nil {
			return "", err
		}
	}
	g.indent--
	g.line("}")
	return g.out.String(), nil
}
func (g *generator) writePreamble() {
	g.line("// Code generated by Aster. DO NOT EDIT.")
	g.line("package main")
	g.line("")
	g.line("import (")
	g.indent++
	g.line("\"fmt\"")
	g.line("\"math\"")
	g.line("\"os\"")
	g.line("\"unicode/utf8\"")
	g.indent--
	g.line(")")
	g.line("")
	g.line("func asterPrint(v any) struct{} { fmt.Println(v); return struct{}{} }")
	g.line("func asterLenString(s string) int64 { return int64(utf8.RuneCountInString(s)) }")
	g.line("func asterAssert(ok bool) struct{} { if !ok { panic(\"assertion failed\") }; return struct{}{} }")
	g.line("const asterMaxI64 int64 = 1<<63 - 1")
	g.line("const asterMinI64 int64 = -1 << 63")
	g.line("func asterAddI64(a,b int64) int64 { if (b>0 && a>asterMaxI64-b)||(b<0 && a<asterMinI64-b) { panic(\"i64 overflow in addition\") }; return a+b }")
	g.line("func asterSubI64(a,b int64) int64 { if (b<0 && a>asterMaxI64+b)||(b>0 && a<asterMinI64+b) { panic(\"i64 overflow in subtraction\") }; return a-b }")
	g.line("func asterMulI64(a,b int64) int64 { if a==0 || b==0 { return 0 }; if (a==asterMinI64 && b==-1)||(b==asterMinI64 && a==-1) { panic(\"i64 overflow in multiplication\") }; z:=a*b; if z/b!=a { panic(\"i64 overflow in multiplication\") }; return z }")
	g.line("func asterDivI64(a,b int64) int64 { if b==0 { panic(\"division by zero\") }; if a==asterMinI64 && b==-1 { panic(\"i64 overflow in division\") }; return a/b }")
	g.line("func asterModI64(a,b int64) int64 { if b==0 { panic(\"remainder by zero\") }; if a==asterMinI64 && b==-1 { return 0 }; return a%b }")
	g.line("func asterNegI64(a int64) int64 { if a==asterMinI64 { panic(\"i64 overflow in unary '-'\") }; return -a }")
	g.line("func asterAddF64(a,b float64) float64 { z:=a+b; if math.IsInf(z,0)||math.IsNaN(z) { panic(\"non-finite floating-point result\") }; return z }")
	g.line("func asterSubF64(a,b float64) float64 { z:=a-b; if math.IsInf(z,0)||math.IsNaN(z) { panic(\"non-finite floating-point result\") }; return z }")
	g.line("func asterMulF64(a,b float64) float64 { z:=a*b; if math.IsInf(z,0)||math.IsNaN(z) { panic(\"non-finite floating-point result\") }; return z }")
	g.line("func asterDivF64(a,b float64) float64 { if b==0 { panic(\"division by zero\") }; z:=a/b; if math.IsInf(z,0)||math.IsNaN(z) { panic(\"non-finite floating-point result\") }; return z }")
	g.line("")
}
func (g *generator) function(f *ast.Function) error {
	g.scope = newTypeScope(nil)
	params := make([]string, 0, len(f.Params))
	for _, p := range f.Params {
		pt := sourceTypeName(p.Type)
		params = append(params, "v_"+p.Name+" "+goType(pt))
		g.scope.types[p.Name] = pt
	}
	ret := g.returns[f.Name]
	g.line(fmt.Sprintf("func asterFn_%s(%s) %s {", f.Name, strings.Join(params, ", "), goType(ret)))
	g.indent++
	if err := g.blockContents(f.Body); err != nil {
		return err
	}
	if ret == "unit" {
		g.line("return struct{}{}")
	}
	g.indent--
	g.line("}")
	g.line("")
	return nil
}
func (g *generator) blockContents(b *ast.BlockStmt) error {
	for _, s := range b.Statements {
		if err := g.statement(s); err != nil {
			return err
		}
	}
	return nil
}
func (g *generator) statement(s ast.Stmt) error {
	switch n := s.(type) {
	case *ast.BlockStmt:
		old := g.scope
		g.scope = newTypeScope(old)
		g.line("{")
		g.indent++
		err := g.blockContents(n)
		g.indent--
		g.line("}")
		g.scope = old
		return err
	case *ast.LetStmt:
		expr, err := g.expression(n.Value)
		if err != nil {
			return err
		}
		t := g.exprType(n.Value)
		if n.Annotation != nil {
			t = n.Annotation.Name
		}
		g.line(fmt.Sprintf("v_%s := %s", n.Name, expr))
		g.line("_ = v_" + n.Name)
		g.scope.types[n.Name] = t
		return nil
	case *ast.AssignStmt:
		expr, err := g.expression(n.Value)
		if err != nil {
			return err
		}
		g.line(fmt.Sprintf("v_%s = %s", n.Name, expr))
		return nil
	case *ast.ExprStmt:
		expr, err := g.expression(n.Expr)
		if err != nil {
			return err
		}
		g.line(expr)
		return nil
	case *ast.IfStmt:
		cond, err := g.expression(n.Condition)
		if err != nil {
			return err
		}
		g.line("if " + cond + " {")
		g.indent++
		old := g.scope
		g.scope = newTypeScope(old)
		err = g.blockContents(n.Then)
		g.scope = old
		g.indent--
		if err != nil {
			return err
		}
		if n.Else != nil {
			g.line("} else {")
			g.indent++
			old = g.scope
			g.scope = newTypeScope(old)
			err = g.statement(n.Else)
			g.scope = old
			g.indent--
			if err != nil {
				return err
			}
			g.line("}")
		} else {
			g.line("}")
		}
		return nil
	case *ast.WhileStmt:
		cond, err := g.expression(n.Condition)
		if err != nil {
			return err
		}
		g.line("for " + cond + " {")
		g.indent++
		old := g.scope
		g.scope = newTypeScope(old)
		err = g.blockContents(n.Body)
		g.scope = old
		g.indent--
		g.line("}")
		return err
	case *ast.ReturnStmt:
		if n.Value == nil {
			g.line("return struct{}{}")
			return nil
		}
		expr, err := g.expression(n.Value)
		if err != nil {
			return err
		}
		g.line("return " + expr)
		return nil
	default:
		return fmt.Errorf("codegen: unsupported statement %T", s)
	}
}
func (g *generator) expression(e ast.Expr) (string, error) {
	switch n := e.(type) {
	case *ast.LiteralExpr:
		switch n.Kind {
		case "i64":
			return "int64(" + strconv.FormatInt(n.Int, 10) + ")", nil
		case "f64":
			return "float64(" + strconv.FormatFloat(n.Float, 'g', -1, 64) + ")", nil
		case "bool":
			return strconv.FormatBool(n.Bool), nil
		case "string":
			return strconv.Quote(n.String), nil
		}
	case *ast.ArrayExpr:
		items := make([]string, len(n.Elements))
		for i, item := range n.Elements {
			x, err := g.expression(item)
			if err != nil {
				return "", err
			}
			items[i] = x
		}
		return goType(g.exprType(n)) + "{" + strings.Join(items, ", ") + "}", nil
	case *ast.IndexExpr:
		collection, err := g.expression(n.Collection)
		if err != nil {
			return "", err
		}
		index, err := g.expression(n.Index)
		if err != nil {
			return "", err
		}
		return "(" + collection + ")[int(" + index + ")]", nil
	case *ast.IdentifierExpr:
		return "v_" + n.Name, nil
	case *ast.UnaryExpr:
		r, err := g.expression(n.Right)
		if err != nil {
			return "", err
		}
		if n.Op == "-" && g.exprType(n.Right) == "i64" {
			return "asterNegI64(" + r + ")", nil
		}
		if n.Op == "!" {
			return "(!" + r + ")", nil
		}
		return "(" + n.Op + r + ")", nil
	case *ast.BinaryExpr:
		l, err := g.expression(n.Left)
		if err != nil {
			return "", err
		}
		r, err := g.expression(n.Right)
		if err != nil {
			return "", err
		}
		t := g.exprType(n.Left)
		if n.Op == "+" && t == "string" {
			return "(" + l + " + " + r + ")", nil
		}
		if t == "i64" {
			helpers := map[string]string{"+": "asterAddI64", "-": "asterSubI64", "*": "asterMulI64", "/": "asterDivI64", "%": "asterModI64"}
			if h, ok := helpers[n.Op]; ok {
				return h + "(" + l + ", " + r + ")", nil
			}
		}
		if t == "f64" {
			helpers := map[string]string{"+": "asterAddF64", "-": "asterSubF64", "*": "asterMulF64", "/": "asterDivF64"}
			if h, ok := helpers[n.Op]; ok {
				return h + "(" + l + ", " + r + ")", nil
			}
		}
		return "(" + l + " " + n.Op + " " + r + ")", nil
	case *ast.CallExpr:
		id, ok := n.Callee.(*ast.IdentifierExpr)
		if !ok {
			return "", fmt.Errorf("codegen: only named functions can be called")
		}
		args := make([]string, len(n.Args))
		for i, a := range n.Args {
			x, err := g.expression(a)
			if err != nil {
				return "", err
			}
			args[i] = x
		}
		joined := strings.Join(args, ", ")
		switch id.Name {
		case "print":
			return "asterPrint(" + joined + ")", nil
		case "len":
			if len(n.Args) == 1 && g.exprType(n.Args[0]) != "string" {
				return "int64(len(" + joined + "))", nil
			}
			return "asterLenString(" + joined + ")", nil
		case "assert":
			return "asterAssert(" + joined + ")", nil
		default:
			return "asterFn_" + id.Name + "(" + joined + ")", nil
		}
	}
	return "", fmt.Errorf("codegen: unsupported expression %T", e)
}
func (g *generator) exprType(e ast.Expr) string {
	switch n := e.(type) {
	case *ast.LiteralExpr:
		return n.Kind
	case *ast.IdentifierExpr:
		if t, ok := g.scope.find(n.Name); ok {
			return t
		}
	case *ast.ArrayExpr:
		if len(n.Elements) > 0 {
			return "Array<" + g.exprType(n.Elements[0]) + ">"
		}
	case *ast.IndexExpr:
		if elem, ok := arrayElementType(g.exprType(n.Collection)); ok {
			return elem
		}
	case *ast.UnaryExpr:
		return g.exprType(n.Right)
	case *ast.BinaryExpr:
		if n.Op == "&&" || n.Op == "||" || n.Op == "==" || n.Op == "!=" || n.Op == "<" || n.Op == "<=" || n.Op == ">" || n.Op == ">=" {
			return "bool"
		}
		return g.exprType(n.Left)
	case *ast.CallExpr:
		if id, ok := n.Callee.(*ast.IdentifierExpr); ok {
			switch id.Name {
			case "print", "assert":
				return "unit"
			case "len":
				return "i64"
			default:
				if r, ok := g.returns[id.Name]; ok {
					return r
				}
			}
		}
	}
	return "unit"
}
func sourceTypeName(t ast.TypeRef) string {
	if t.Element != nil {
		return t.Name + "<" + sourceTypeName(*t.Element) + ">"
	}
	return t.Name
}

func goType(t string) string {
	switch t {
	case "i64":
		return "int64"
	case "f64":
		return "float64"
	case "bool":
		return "bool"
	case "string":
		return "string"
	default:
		if elem, ok := arrayElementType(t); ok {
			return "[]" + goType(elem)
		}
		return "struct{}"
	}
}
func arrayElementType(t string) (string, bool) {
	if strings.HasPrefix(t, "Array<") && strings.HasSuffix(t, ">") {
		return t[len("Array<") : len(t)-1], true
	}
	return "", false
}
func (g *generator) line(s string) {
	g.out.WriteString(strings.Repeat("\t", g.indent))
	g.out.WriteString(s)
	g.out.WriteByte('\n')
}
