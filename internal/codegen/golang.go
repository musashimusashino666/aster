// Package codegen lowers the normalized, type-checked Aster IR to a self-contained Go program.
// The Go backend is an initial native backend; generated executables include
// Aster runtime checks rather than relying on unchecked Go arithmetic.
package codegen

import (
	"bytes"
	"fmt"
	"strings"

	"github.com/aster-lang/aster/internal/ast"
	"github.com/aster-lang/aster/internal/checker"
	"github.com/aster-lang/aster/internal/langtypes"
	"github.com/aster-lang/aster/internal/limits"
)

type generator struct {
	out    bytes.Buffer
	indent int
}

// Generate returns native-backend source. The resulting file can be compiled by
// the Go toolchain; users of Aster do not need to edit the generated source.
// Generate type-checks tree and lowers the resulting typed program to Go.
// Call GenerateTyped when the checker result is already available.
func Generate(tree *ast.Program) (string, error) {
	typed, err := checker.Analyze(tree)
	if err != nil {
		return "", err
	}
	return GenerateTyped(typed)
}

// GenerateTyped lowers the checker's normalized IR to Go. Expression types,
// resolved symbols, function targets, and checked operations come from the checker phase.
func GenerateTyped(typed *checker.TypedProgram) (string, error) {
	if typed == nil {
		return "", fmt.Errorf("codegen: nil typed program")
	}
	if typed.IR == nil {
		return "", fmt.Errorf("codegen: typed program has no normalized IR")
	}
	g := &generator{}
	for _, fn := range typed.IR.Functions {
		ret := string(fn.ReturnType)
		if !langtypes.ValidName(ret) {
			return "", fmt.Errorf("codegen: invalid IR return type %q for function %q", ret, fn.Name)
		}
		for _, param := range fn.Params {
			name := string(param.Type)
			if !langtypes.ValidName(name) || name == string(checker.Unit) {
				return "", fmt.Errorf("codegen: invalid IR parameter type %q for function %q", name, fn.Name)
			}
		}
	}
	g.writePreamble()
	for _, f := range typed.IR.Functions {
		if err := g.irFunction(f); err != nil {
			return "", err
		}
	}
	g.line("func main() {")
	g.indent++
	g.line("defer func() { if r := recover(); r != nil { msg := fmt.Sprint(r); if !strings.Contains(msg, \"runtime error:\") { msg = \"runtime error: \" + msg }; fmt.Fprintln(os.Stderr, msg); os.Exit(1) } }()")
	for _, stmt := range typed.IR.Body {
		if err := g.irStatement(stmt); err != nil {
			return "", err
		}
	}
	g.indent--
	g.line("}")
	return g.out.String(), nil
}
func (g *generator) writePreamble() {
	g.line("// Code generated by Aster. DO NOT EDIT.")
	g.line("package main")
	g.line("")
	g.line("import (")
	g.indent++
	g.line("\"fmt\"")
	g.line("\"math\"")
	g.line("\"os\"")
	g.line("\"reflect\"")
	g.line("\"strings\"")
	g.line("\"unicode/utf8\"")
	g.indent--
	g.line(")")
	g.line("")
	g.line("func asterPrint(v any, line, column int) struct{} { var out strings.Builder; asterFormatValue(reflect.ValueOf(v), &out, line, column, 0); if _, err := fmt.Fprintln(os.Stdout, out.String()); err != nil { asterRuntimeError(line, column, fmt.Sprintf(\"write output: %v\", err)) }; return struct{}{} }")
	g.line("func asterLenString(s string) int64 { return int64(utf8.RuneCountInString(s)) }")
	g.line(fmt.Sprintf("const asterMaxStringBytes = %d", limits.MaxStringBytes))
	g.line(fmt.Sprintf("const asterMaxArrayNestingDepth = %d", limits.MaxArrayNestingDepth))
	g.line("func asterDisplayWrite(out *strings.Builder, text string, line, column int) { if len(text) > asterMaxStringBytes-out.Len() { asterRuntimeError(line, column, fmt.Sprintf(\"printed value exceeds %d-byte output limit\", asterMaxStringBytes)) }; out.WriteString(text) }")
	g.line("func asterFormatValue(value reflect.Value, out *strings.Builder, line, column, depth int) { if value.Kind() == reflect.Slice { if depth >= asterMaxArrayNestingDepth && value.Len() > 0 { asterRuntimeError(line, column, \"printed array nesting exceeds depth limit\") }; asterDisplayWrite(out, \"[\", line, column); for i := 0; i < value.Len(); i++ { if i > 0 { asterDisplayWrite(out, \" \", line, column) }; asterFormatValue(value.Index(i), out, line, column, depth+1) }; asterDisplayWrite(out, \"]\", line, column); return }; if value.Kind() == reflect.String { asterDisplayWrite(out, value.String(), line, column); return }; asterDisplayWrite(out, fmt.Sprint(value.Interface()), line, column) }")
	g.line("func asterAddString(a, b string, line, column int) string { if len(b) > asterMaxStringBytes || len(a) > asterMaxStringBytes-len(b) { asterRuntimeError(line, column, fmt.Sprintf(\"string length limit exceeded (maximum %d UTF-8 bytes)\", asterMaxStringBytes)) }; return a+b }")
	g.line("func asterRuntimeError(line, column int, message string) { if line > 0 && column > 0 { panic(fmt.Sprintf(\"%d:%d: runtime error: %s\", line, column, message)) }; panic(\"runtime error: \" + message) }")
	g.line("func asterAssert(ok bool, line, column int) struct{} { if !ok { asterRuntimeError(line, column, \"assertion failed\") }; return struct{}{} }")
	g.line("func asterIndexI64[T any](s []T, i int64, line, column int) T { if i < 0 || i >= int64(len(s)) { asterRuntimeError(line, column, fmt.Sprintf(\"array index %d out of bounds for length %d\", i, len(s))) }; return s[int(i)] }")
	g.line("const asterMaxI64 int64 = 1<<63 - 1")
	g.line("const asterMinI64 int64 = -1 << 63")
	g.line("func asterAddI64(a,b int64, line,column int) int64 { if (b>0 && a>asterMaxI64-b)||(b<0 && a<asterMinI64-b) { asterRuntimeError(line,column, \"i64 overflow in addition\") }; return a+b }")
	g.line("func asterSubI64(a,b int64, line,column int) int64 { if (b<0 && a>asterMaxI64+b)||(b>0 && a<asterMinI64+b) { asterRuntimeError(line,column, \"i64 overflow in subtraction\") }; return a-b }")
	g.line("func asterMulI64(a,b int64, line,column int) int64 { if a==0 || b==0 { return 0 }; if (a==asterMinI64 && b==-1)||(b==asterMinI64 && a==-1) { asterRuntimeError(line,column, \"i64 overflow in multiplication\") }; z:=a*b; if z/b!=a { asterRuntimeError(line,column, \"i64 overflow in multiplication\") }; return z }")
	g.line("func asterDivI64(a,b int64, line,column int) int64 { if b==0 { asterRuntimeError(line,column, \"division by zero\") }; if a==asterMinI64 && b==-1 { asterRuntimeError(line,column, \"i64 overflow in division\") }; return a/b }")
	g.line("func asterModI64(a,b int64, line,column int) int64 { if b==0 { asterRuntimeError(line,column, \"remainder by zero\") }; if a==asterMinI64 && b==-1 { return 0 }; return a%b }")
	g.line("func asterNegI64(a int64, line,column int) int64 { if a==asterMinI64 { asterRuntimeError(line,column, \"integer overflow in unary '-'\") }; return -a }")
	g.line("func asterAddF64(a,b float64, line,column int) float64 { z:=a+b; if math.IsInf(z,0)||math.IsNaN(z) { asterRuntimeError(line,column, \"non-finite floating-point result\") }; return z }")
	g.line("func asterSubF64(a,b float64, line,column int) float64 { z:=a-b; if math.IsInf(z,0)||math.IsNaN(z) { asterRuntimeError(line,column, \"non-finite floating-point result\") }; return z }")
	g.line("func asterMulF64(a,b float64, line,column int) float64 { z:=a*b; if math.IsInf(z,0)||math.IsNaN(z) { asterRuntimeError(line,column, \"non-finite floating-point result\") }; return z }")
	g.line("func asterDivF64(a,b float64, line,column int) float64 { if b==0 { asterRuntimeError(line,column, \"division by zero\") }; z:=a/b; if math.IsInf(z,0)||math.IsNaN(z) { asterRuntimeError(line,column, \"non-finite floating-point result\") }; return z }")
	g.line("")
}
func goType(t string) string {
	switch t {
	case "i64":
		return "int64"
	case "f64":
		return "float64"
	case "bool":
		return "bool"
	case "string":
		return "string"
	default:
		if elem, ok := arrayElementType(t); ok {
			return "[]" + goType(elem)
		}
		return "struct{}"
	}
}
func arrayElementType(t string) (string, bool) {
	if strings.HasPrefix(t, "Array<") && strings.HasSuffix(t, ">") {
		return t[len("Array<") : len(t)-1], true
	}
	return "", false
}
func (g *generator) line(s string) {
	g.out.WriteString(strings.Repeat("\t", g.indent))
	g.out.WriteString(s)
	g.out.WriteByte('\n')
}
