// Package codegen lowers the type-checked Aster AST to a self-contained Go program.
// The Go backend is an initial native backend; generated executables include
// Aster runtime checks rather than relying on unchecked Go arithmetic.
package codegen

import (
	"bytes"
	"fmt"
	"strconv"
	"strings"

	"github.com/aster-lang/aster/internal/ast"
	"github.com/aster-lang/aster/internal/checker"
	"github.com/aster-lang/aster/internal/langtypes"
	"github.com/aster-lang/aster/internal/limits"
)

type generator struct {
	typed  *checker.TypedProgram
	tree   *ast.Program
	out    bytes.Buffer
	indent int
}

// Generate returns native-backend source. The resulting file can be compiled by
// the Go toolchain; users of Aster do not need to edit the generated source.
// Generate type-checks tree and lowers the resulting typed program to Go.
// Call GenerateTyped when the checker result is already available.
func Generate(tree *ast.Program) (string, error) {
	typed, err := checker.Analyze(tree)
	if err != nil {
		return "", err
	}
	return GenerateTyped(typed)
}

// GenerateTyped lowers checker-produced semantic metadata and its AST to Go.
// Expression types and function signatures are read from the checker result;
// the native backend does not independently re-infer them.
func GenerateTyped(typed *checker.TypedProgram) (string, error) {
	if typed == nil || typed.Tree == nil {
		return "", fmt.Errorf("codegen: nil typed program")
	}
	tree := typed.Tree
	g := &generator{typed: typed, tree: tree}
	for _, d := range tree.Decls {
		f, ok := d.(*ast.Function)
		if !ok {
			continue
		}
		info, ok := typed.Function(f.Name)
		if !ok {
			return "", fmt.Errorf("codegen: checker has no signature for function %q", f.Name)
		}
		ret := info.Return.String()
		if !langtypes.ValidName(ret) {
			return "", fmt.Errorf("codegen: invalid return type %q for function %q", ret, f.Name)
		}
		if len(info.Params) != len(f.Params) {
			return "", fmt.Errorf("codegen: checker parameter count mismatch for function %q", f.Name)
		}
		for _, paramType := range info.Params {
			name := paramType.String()
			if !langtypes.ValidName(name) || paramType == checker.Unit {
				return "", fmt.Errorf("codegen: invalid parameter type %q for function %q", name, f.Name)
			}
		}
	}
	g.writePreamble()
	for _, d := range tree.Decls {
		f, ok := d.(*ast.Function)
		if !ok {
			continue
		}
		if err := g.function(f); err != nil {
			return "", err
		}
	}
	g.line("func main() {")
	g.indent++
	g.line("defer func() { if r := recover(); r != nil { msg := fmt.Sprint(r); if !strings.Contains(msg, \"runtime error:\") { msg = \"runtime error: \" + msg }; fmt.Fprintln(os.Stderr, msg); os.Exit(1) } }()")
	for _, d := range tree.Decls {
		sd, ok := d.(*ast.StmtDecl)
		if !ok {
			continue
		}
		if err := g.statement(sd.Statement); err != nil {
			return "", err
		}
	}
	g.indent--
	g.line("}")
	return g.out.String(), nil
}
func (g *generator) writePreamble() {
	g.line("// Code generated by Aster. DO NOT EDIT.")
	g.line("package main")
	g.line("")
	g.line("import (")
	g.indent++
	g.line("\"fmt\"")
	g.line("\"math\"")
	g.line("\"os\"")
	g.line("\"strings\"")
	g.line("\"unicode/utf8\"")
	g.indent--
	g.line(")")
	g.line("")
	g.line("func asterPrint(v any, line, column int) struct{} { if _, err := fmt.Fprintln(os.Stdout, v); err != nil { asterRuntimeError(line, column, fmt.Sprintf(\"write output: %v\", err)) }; return struct{}{} }")
	g.line("func asterLenString(s string) int64 { return int64(utf8.RuneCountInString(s)) }")
	g.line(fmt.Sprintf("const asterMaxStringBytes = %d", limits.MaxStringBytes))
	g.line("func asterAddString(a, b string, line, column int) string { if len(b) > asterMaxStringBytes || len(a) > asterMaxStringBytes-len(b) { asterRuntimeError(line, column, fmt.Sprintf(\"string length limit exceeded (maximum %d UTF-8 bytes)\", asterMaxStringBytes)) }; return a+b }")
	g.line("func asterRuntimeError(line, column int, message string) { if line > 0 && column > 0 { panic(fmt.Sprintf(\"%d:%d: runtime error: %s\", line, column, message)) }; panic(\"runtime error: \" + message) }")
	g.line("func asterAssert(ok bool, line, column int) struct{} { if !ok { asterRuntimeError(line, column, \"assertion failed\") }; return struct{}{} }")
	g.line("func asterIndexI64[T any](s []T, i int64, line, column int) T { if i < 0 || i >= int64(len(s)) { asterRuntimeError(line, column, fmt.Sprintf(\"array index %d out of bounds for length %d\", i, len(s))) }; return s[int(i)] }")
	g.line("const asterMaxI64 int64 = 1<<63 - 1")
	g.line("const asterMinI64 int64 = -1 << 63")
	g.line("func asterAddI64(a,b int64, line,column int) int64 { if (b>0 && a>asterMaxI64-b)||(b<0 && a<asterMinI64-b) { asterRuntimeError(line,column, \"i64 overflow in addition\") }; return a+b }")
	g.line("func asterSubI64(a,b int64, line,column int) int64 { if (b<0 && a>asterMaxI64+b)||(b>0 && a<asterMinI64+b) { asterRuntimeError(line,column, \"i64 overflow in subtraction\") }; return a-b }")
	g.line("func asterMulI64(a,b int64, line,column int) int64 { if a==0 || b==0 { return 0 }; if (a==asterMinI64 && b==-1)||(b==asterMinI64 && a==-1) { asterRuntimeError(line,column, \"i64 overflow in multiplication\") }; z:=a*b; if z/b!=a { asterRuntimeError(line,column, \"i64 overflow in multiplication\") }; return z }")
	g.line("func asterDivI64(a,b int64, line,column int) int64 { if b==0 { asterRuntimeError(line,column, \"division by zero\") }; if a==asterMinI64 && b==-1 { asterRuntimeError(line,column, \"i64 overflow in division\") }; return a/b }")
	g.line("func asterModI64(a,b int64, line,column int) int64 { if b==0 { asterRuntimeError(line,column, \"remainder by zero\") }; if a==asterMinI64 && b==-1 { return 0 }; return a%b }")
	g.line("func asterNegI64(a int64, line,column int) int64 { if a==asterMinI64 { asterRuntimeError(line,column, \"integer overflow in unary '-'\") }; return -a }")
	g.line("func asterAddF64(a,b float64, line,column int) float64 { z:=a+b; if math.IsInf(z,0)||math.IsNaN(z) { asterRuntimeError(line,column, \"non-finite floating-point result\") }; return z }")
	g.line("func asterSubF64(a,b float64, line,column int) float64 { z:=a-b; if math.IsInf(z,0)||math.IsNaN(z) { asterRuntimeError(line,column, \"non-finite floating-point result\") }; return z }")
	g.line("func asterMulF64(a,b float64, line,column int) float64 { z:=a*b; if math.IsInf(z,0)||math.IsNaN(z) { asterRuntimeError(line,column, \"non-finite floating-point result\") }; return z }")
	g.line("func asterDivF64(a,b float64, line,column int) float64 { if b==0 { asterRuntimeError(line,column, \"division by zero\") }; z:=a/b; if math.IsInf(z,0)||math.IsNaN(z) { asterRuntimeError(line,column, \"non-finite floating-point result\") }; return z }")
	g.line("")
}
func (g *generator) function(f *ast.Function) error {
	info, ok := g.typed.Function(f.Name)
	if !ok {
		return fmt.Errorf("codegen: checker has no signature for function %q", f.Name)
	}
	params := make([]string, 0, len(f.Params))
	for i, p := range f.Params {
		pt := info.Params[i].String()
		params = append(params, "v_"+p.Name+" "+goType(pt))
	}
	ret := info.Return.String()
	g.line(fmt.Sprintf("func asterFn_%s(%s) %s {", f.Name, strings.Join(params, ", "), goType(ret)))
	g.indent++
	if err := g.blockContents(f.Body); err != nil {
		return err
	}
	if ret == "unit" {
		g.line("return struct{}{}")
	}
	g.indent--
	g.line("}")
	g.line("")
	return nil
}
func (g *generator) blockContents(b *ast.BlockStmt) error {
	for _, s := range b.Statements {
		if err := g.statement(s); err != nil {
			return err
		}
	}
	return nil
}
func (g *generator) statement(s ast.Stmt) error {
	switch n := s.(type) {
	case *ast.BlockStmt:
		g.line("{")
		g.indent++
		err := g.blockContents(n)
		g.indent--
		g.line("}")
		return err
	case *ast.LetStmt:
		expr, err := g.expression(n.Value)
		if err != nil {
			return err
		}
		t, err := g.typeOf(n.Value)
		if err != nil {
			return fmt.Errorf("codegen: infer initializer type for %q: %w", n.Name, err)
		}
		if !langtypes.ValidName(t) || t == "unit" {
			return fmt.Errorf("codegen: invalid variable type %q for %q", t, n.Name)
		}
		g.line(fmt.Sprintf("v_%s := %s", n.Name, expr))
		g.line("_ = v_" + n.Name)
		return nil
	case *ast.AssignStmt:
		expr, err := g.expression(n.Value)
		if err != nil {
			return err
		}
		g.line(fmt.Sprintf("v_%s = %s", n.Name, expr))
		return nil
	case *ast.ExprStmt:
		expr, err := g.expression(n.Expr)
		if err != nil {
			return err
		}
		// Go only permits certain call expressions as statements. Assigning the
		// value to the blank identifier preserves evaluation for all Aster
		// expression statements (including pure expressions and unit calls).
		g.line("_ = " + expr)
		return nil
	case *ast.IfStmt:
		cond, err := g.expression(n.Condition)
		if err != nil {
			return err
		}
		g.line("if " + cond + " {")
		g.indent++
		err = g.blockContents(n.Then)
		g.indent--
		if err != nil {
			return err
		}
		if n.Else != nil {
			g.line("} else {")
			g.indent++
			err = g.statement(n.Else)
			g.indent--
			if err != nil {
				return err
			}
			g.line("}")
		} else {
			g.line("}")
		}
		return nil
	case *ast.WhileStmt:
		cond, err := g.expression(n.Condition)
		if err != nil {
			return err
		}
		g.line("for " + cond + " {")
		g.indent++
		err = g.blockContents(n.Body)
		g.indent--
		g.line("}")
		return err
	case *ast.ReturnStmt:
		if n.Value == nil {
			g.line("return struct{}{}")
			return nil
		}
		expr, err := g.expression(n.Value)
		if err != nil {
			return err
		}
		g.line("return " + expr)
		return nil
	default:
		return fmt.Errorf("codegen: unsupported statement %T", s)
	}
}
func (g *generator) expression(e ast.Expr) (string, error) {
	switch n := e.(type) {
	case *ast.LiteralExpr:
		switch n.Kind {
		case "i64":
			return "int64(" + strconv.FormatInt(n.Int, 10) + ")", nil
		case "f64":
			return "float64(" + strconv.FormatFloat(n.Float, 'g', -1, 64) + ")", nil
		case "bool":
			return strconv.FormatBool(n.Bool), nil
		case "string":
			if len(n.String) > limits.MaxStringBytes {
				pos := n.Pos()
				return "", fmt.Errorf("%d:%d: codegen: string literal exceeds %d-byte limit", pos.Line, pos.Column, limits.MaxStringBytes)
			}
			return strconv.Quote(n.String), nil
		}
	case *ast.ArrayExpr:
		if len(n.Elements) > limits.MaxArrayLength {
			pos := n.Pos()
			return "", fmt.Errorf("%d:%d: codegen: array literal has %d elements; maximum is %d", pos.Line, pos.Column, len(n.Elements), limits.MaxArrayLength)
		}
		items := make([]string, len(n.Elements))
		for i, item := range n.Elements {
			x, err := g.expression(item)
			if err != nil {
				return "", err
			}
			items[i] = x
		}
		arrayType, err := g.typeOf(n)
		if err != nil {
			return "", err
		}
		return goType(arrayType) + "{" + strings.Join(items, ", ") + "}", nil
	case *ast.IndexExpr:
		collection, err := g.expression(n.Collection)
		if err != nil {
			return "", err
		}
		index, err := g.expression(n.Index)
		if err != nil {
			return "", err
		}
		return "asterIndexI64(" + collection + ", " + index + ", " + positionArgs(n) + ")", nil
	case *ast.IdentifierExpr:
		return "v_" + n.Name, nil
	case *ast.UnaryExpr:
		r, err := g.expression(n.Right)
		if err != nil {
			return "", err
		}
		if n.Op == "-" {
			rightType, err := g.typeOf(n.Right)
			if err != nil {
				return "", err
			}
			if rightType == "i64" {
				return "asterNegI64(" + r + ", " + positionArgs(n) + ")", nil
			}
		}
		if n.Op == "!" {
			return "(!" + r + ")", nil
		}
		return "(" + n.Op + r + ")", nil
	case *ast.BinaryExpr:
		l, err := g.expression(n.Left)
		if err != nil {
			return "", err
		}
		r, err := g.expression(n.Right)
		if err != nil {
			return "", err
		}
		t, err := g.typeOf(n.Left)
		if err != nil {
			return "", err
		}
		if n.Op == "+" && t == "string" {
			return "asterAddString(" + l + ", " + r + ", " + positionArgs(n) + ")", nil
		}
		if t == "i64" {
			helpers := map[string]string{"+": "asterAddI64", "-": "asterSubI64", "*": "asterMulI64", "/": "asterDivI64", "%": "asterModI64"}
			if h, ok := helpers[n.Op]; ok {
				return h + "(" + l + ", " + r + ", " + positionArgs(n) + ")", nil
			}
		}
		if t == "f64" {
			helpers := map[string]string{"+": "asterAddF64", "-": "asterSubF64", "*": "asterMulF64", "/": "asterDivF64"}
			if h, ok := helpers[n.Op]; ok {
				return h + "(" + l + ", " + r + ", " + positionArgs(n) + ")", nil
			}
		}
		return "(" + l + " " + n.Op + " " + r + ")", nil
	case *ast.CallExpr:
		id, ok := n.Callee.(*ast.IdentifierExpr)
		if !ok {
			return "", fmt.Errorf("codegen: only named functions can be called")
		}
		args := make([]string, len(n.Args))
		for i, a := range n.Args {
			x, err := g.expression(a)
			if err != nil {
				return "", err
			}
			args[i] = x
		}
		joined := strings.Join(args, ", ")
		switch id.Name {
		case "print":
			return "asterPrint(" + joined + ", " + positionArgs(n) + ")", nil
		case "len":
			if len(n.Args) == 1 {
				argType, err := g.typeOf(n.Args[0])
				if err != nil {
					return "", err
				}
				if argType != "string" {
					return "int64(len(" + joined + "))", nil
				}
			}
			return "asterLenString(" + joined + ")", nil
		case "assert":
			return "asterAssert(" + joined + ", " + positionArgs(n) + ")", nil
		default:
			return "asterFn_" + id.Name + "(" + joined + ")", nil
		}
	}
	return "", fmt.Errorf("codegen: unsupported expression %T", e)
}
func (g *generator) typeOf(e ast.Expr) (string, error) {
	t, ok := g.typed.TypeOf(e)
	if !ok {
		return "", fmt.Errorf("codegen: checker has no type for expression %T", e)
	}
	return t.String(), nil
}

func positionArgs(node ast.Node) string {
	pos := node.Pos()
	return fmt.Sprintf("%d, %d", pos.Line, pos.Column)
}

func goType(t string) string {
	switch t {
	case "i64":
		return "int64"
	case "f64":
		return "float64"
	case "bool":
		return "bool"
	case "string":
		return "string"
	default:
		if elem, ok := arrayElementType(t); ok {
			return "[]" + goType(elem)
		}
		return "struct{}"
	}
}
func arrayElementType(t string) (string, bool) {
	if strings.HasPrefix(t, "Array<") && strings.HasSuffix(t, ">") {
		return t[len("Array<") : len(t)-1], true
	}
	return "", false
}
func (g *generator) line(s string) {
	g.out.WriteString(strings.Repeat("\t", g.indent))
	g.out.WriteString(s)
	g.out.WriteByte('\n')
}
